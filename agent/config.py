"""
config.py
---------
نقطة مركزية واحدة لكل الإعدادات. أي جزء من النظام يحتاج مفتاح API،
اسم الموديل، أو مسار قاعدة البيانات يقرأ من هنا، عشان لو غيّرنا حاجة
منغيّرهاش في عشر أماكن.
"""

import os
from dataclasses import dataclass, field
from pathlib import Path

BASE_DIR = Path(__file__).resolve().parent.parent
DATA_DIR = BASE_DIR / "data"
DATA_DIR.mkdir(exist_ok=True)


@dataclass(frozen=True)
class Settings:
    # مفتاح الـ API لـ Google Gemini
    google_api_key: str = field(default_factory=lambda: os.environ.get("GOOGLE_API_KEY", ""))

    # الموديل المستخدم في حلقة الوكيل (Agent Loop)
    # نستخدم Gemini 1.5 Flash لسرعته الفائقة مع الأدوات
    model: str = "gemini-3.5-flash"

    # أقصى عدد توكينز للرد الواحد
    max_tokens: int = 4096

    # أقصى عدد "لفّات" (turns) داخل الحلقة الواحدة قبل ما نوقف
    # عشان نمنع loop لا نهائي لو الموديل فضل يستدعي أدوات لحد ما يخلص التوكينز
    max_agent_turns: int = 25

    # مسار قاعدة بيانات الذاكرة الدائمة
    db_path: str = str(DATA_DIR / "jarvis_memory.db")

    # اسم الوكيل، وشخصيته الأساسية (System Prompt الجذري)
    agent_name: str = "Jarvis"

    system_prompt: str = (
        "أنت مساعد شخصي ذكي اسمه {name}، بتتصرف بشكل استباقي ودقيق، "
        "بتنفذ المهام فعليًا عن طريق الأدوات المتاحة ليك بدل ما ترد بكلام بس. "
        "لو محتاج معلومة أو تنفيذ حاجة، استخدم الأداة المناسبة بدل ما تخمّن. "
        "احتفظ بالحقائق المهمة عن المستخدم في الذاكرة الدائمة لما يطلب منك كده "
        "أو لما تكتشف معلومة هتفيدك في المستقبل.\n\n"
        "قاعدة اللغة: ردّ دائمًا بالعربية (اللهجة المصرية) كلغة أساسية. "
        "لو المستخدم كلمك بالإنجليزية، رد بالإنجليزية. "
        "لو المحتوى تقني، استخدم المصطلحات الإنجليزية التقنية كما هي داخل الرد العربي. "
        "اجعل ردودك مختصرة وعملية قدر الإمكان.\n\n"
        "قاعدة مهمة جدًا: أي إجراء لا يمكن التراجع عنه بسهولة أو مؤثر على نطاق واسع "
        "(زي gmail_bulk_clean بـ action='trash' على عدد كبير من الرسائل، إغلاق الجهاز "
        "(shutdown_computer)، نقل/حذف ملفات على نطاق واسع (organize_by_extension، "
        "move_file، move_to_trash)، أو أي إجراء هيغيّر حاجة حقيقية في حساب المستخدم أو "
        "جهازه) يجب أولاً عرض ملخص واضح لما سيحدث (كام ملف، إيه هي، هيتحرك فين) "
        "وانتظار تأكيد صريح من المستخدم قبل التنفيذ. لا تفترض الموافقة أبدًا في هذه الحالات. "
        "بالنسبة لـ organize_by_extension تحديدًا: استخدم dry_run=True دايمًا الأول واعرض "
        "الخطة، ومتستخدمش dry_run=False إلا بعد موافقة صريحة.\n\n"
        "قاعدة صارمة وغير قابلة للتفاوض بخصوص المال: ممنوع تمامًا عليك تنفيذ أو المساعدة "
        "في تنفيذ أي معاملة مالية من أي نوع - تحويلات، مدفوعات، عمليات شراء، الوصول لحسابات "
        "بنكية أو محافظ رقمية أو عملات مشفرة، أو أي إجراء له أثر مالي مباشر - حتى لو طلب "
        "المستخدم ذلك صراحة أو ألحّ عليك. أخبره بوضوح إن ده خارج نطاق صلاحياتك بدل التنفيذ. "
        "بالإضافة لذلك، ممنوع عليك حفظ أي بيانات مالية حساسة في الذاكرة الدائمة (أرقام بطاقات، "
        "كلمات سر، أرقام حسابات بنكية، رموز تحقق) حتى لو طُلب منك ذلك صراحة."
    )

    def rendered_system_prompt(self) -> str:
        return self.system_prompt.format(name=self.agent_name)


settings = Settings()
